import assert from "node:assert/strict";
import { test } from "node:test";

import { rewriteImports, rewriteSpecifier } from "./transform.ts";

const aliases = {
  components: "@/comps",
  ui: "@/comps/ui",
  hooks: "@/hooks",
  lib: "~/lib",
};

test("rewriteSpecifier maps placeholders to consumer aliases", () => {
  assert.equal(rewriteSpecifier("@/components/ui/button", aliases), "@/comps/ui/button");
  assert.equal(rewriteSpecifier("@/components/data-card", aliases), "@/comps/data-card");
  assert.equal(rewriteSpecifier("@/hooks/use-mobile", aliases), "@/hooks/use-mobile");
  assert.equal(rewriteSpecifier("@/lib/cn", aliases), "~/lib/cn");
});

test("rewriteSpecifier leaves npm and relative imports untouched", () => {
  assert.equal(rewriteSpecifier("react", aliases), "react");
  assert.equal(rewriteSpecifier("@base-ui/react/button", aliases), "@base-ui/react/button");
  assert.equal(rewriteSpecifier("./helper", aliases), "./helper");
});

test("rewriteImports rewrites import and export declarations", () => {
  const content = [
    'import { cn } from "@/lib/cn";',
    'import { Button } from "@/components/ui/button";',
    'import { useIsMobile } from "@/hooks/use-mobile";',
    'import * as React from "react";',
    'import { helper } from "./helper";',
    'export { Badge } from "@/components/ui/badge";',
    "",
  ].join("\n");

  const result = rewriteImports(content, aliases);

  assert.match(result, /from "~\/lib\/cn"/);
  assert.match(result, /from "@\/comps\/ui\/button"/);
  assert.match(result, /from "@\/hooks\/use-mobile"/);
  assert.match(result, /from "react"/);
  assert.match(result, /from "\.\/helper"/);
  assert.match(result, /export \{ Badge \} from "@\/comps\/ui\/badge"/);
});

test("rewriteImports handles side-effect and dynamic imports", () => {
  const content = [
    'import "@/lib/cn";',
    'const mod = await import("@/hooks/use-mobile");',
    'const content = await import("./content.mdx");',
    "",
  ].join("\n");

  const result = rewriteImports(content, aliases);

  assert.match(result, /import "~\/lib\/cn";/);
  assert.match(result, /import\("@\/hooks\/use-mobile"\)/);
  assert.match(result, /import\("\.\/content\.mdx"\)/);
});

test("rewriteImports preserves the original quote style", () => {
  const result = rewriteImports("import { cn } from '@/lib/cn';", aliases);
  assert.match(result, /from '~\/lib\/cn'/);
});

test("rewriteImports leaves the rest of the file untouched", () => {
  const content = [
    "// generated by zbmui — do not edit",
    'const docsUrl = "https://example.com/docs/from/@/lib/cn";',
    "export function App() {",
    '  return <div className={cn("from @/lib/cn")}>hi</div>;',
    "}",
    "",
  ].join("\n");

  const result = rewriteImports(content, aliases);

  assert.equal(result, content);
});
